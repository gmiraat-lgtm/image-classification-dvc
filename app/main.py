@app.get("/health")
def health():
    return {
        "status": "ok",
        "version": APP_VERSION,
        "model": type(MODEL).__name__,
        "features": f"PCA-{N_COMPONENTS}",
        "test_accuracy": TEST_ACCURACY,
        "test_samples_available": int(len(Y_TEST)),
    }


@app.post("/predict")
async def predict(file: UploadFile = File(...)):
    data = await file.read()
    try:
        image = Image.open(io.BytesIO(data))
        image.load()
    except Exception:
        raise HTTPException(status_code=400, detail="The uploaded file is not a readable image")
    result = classify(to_model_input(image))
    result["filename"] = file.filename
    return result


@app.get("/sample")
def sample():
    idx = random.randrange(len(Y_TEST))
    true_label = int(Y_TEST[idx])
    result = classify(X_TEST[idx:idx + 1])
    result["test_index"] = idx
    result["true_label"] = true_label
    result["true_class"] = CLASS_NAMES[true_label]
    result["correct"] = result["predicted_label"] == true_label
    return result


