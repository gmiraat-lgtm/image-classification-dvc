def to_model_input(image):
    """Convert any uploaded image into a 1 x 784 vector in Fashion-MNIST form.

    Fashion-MNIST garments are bright on a black background, centred, and
    fill the 28x28 frame along their longer side, so an ordinary photo is
    converted the same way: grayscale, inverted when its background is
    light, cropped to the garment, resized and centred on a black canvas.
    An image that is already 28x28 is used as it is after the inversion
    check, so a genuine Fashion-MNIST image reaches the model unchanged.
    """
    gray = ImageOps.exif_transpose(image).convert("L")
    arr = np.asarray(gray, dtype=np.float32)
    border = np.concatenate([arr[0, :], arr[-1, :], arr[:, 0], arr[:, -1]])
    if border.mean() > 127:
        gray = ImageOps.invert(gray)

    if gray.size != (IMAGE_SIZE, IMAGE_SIZE):
        gray = ImageOps.autocontrast(gray)
        arr = np.asarray(gray)
        mask = arr > 30
        if mask.any():
            rows = np.where(mask.any(axis=1))[0]
            cols = np.where(mask.any(axis=0))[0]
            gray = gray.crop((int(cols[0]), int(rows[0]), int(cols[-1]) + 1, int(rows[-1]) + 1))

        w, h = gray.size
        scale = IMAGE_SIZE / max(w, h)
        new_w, new_h = max(1, round(w * scale)), max(1, round(h * scale))
        gray = gray.resize((new_w, new_h), Image.LANCZOS)
        canvas = Image.new("L", (IMAGE_SIZE, IMAGE_SIZE), 0)
        canvas.paste(gray, ((IMAGE_SIZE - new_w) // 2, (IMAGE_SIZE - new_h) // 2))
        gray = canvas

    return (np.asarray(gray, dtype=np.float32) / 255.0).reshape(1, -1)


def to_png_base64(x):
    """Render the 784-pixel vector the model actually sees as an enlarged PNG."""
    img = Image.fromarray((x.reshape(IMAGE_SIZE, IMAGE_SIZE) * 255).clip(0, 255).astype(np.uint8))
    img = img.resize((140, 140), Image.NEAREST)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode("ascii")


def classify(x):
    """PCA transform followed by the MLP; returns the top-3 classes."""
    proba = MODEL.predict_proba(SELECTOR.transform(x))[0]
    order = np.argsort(proba)[::-1][:3]
    top3 = []
    for i in order:
        label = int(MODEL.classes_[i])
        top3.append({
            "label": label,
            "class_name": CLASS_NAMES[label],
            "probability": round(float(proba[i]), 4),
        })
    return {
        "predicted_label": top3[0]["label"],
        "predicted_class": top3[0]["class_name"],
        "confidence": top3[0]["probability"],
        "top3": top3,
        "model_input_png": to_png_base64(x),
    }


